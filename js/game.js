      const c1 = Math.floor(b.rect.x / TILE), c2 = Math.floor((b.rect.x + b.rect.w - 0.01) / TILE), r1 = Math.floor(b.rect.y / TILE), r2 = Math.floor((b.rect.y + b.rect.h - 0.01) / TILE);
